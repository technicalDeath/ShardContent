"""Builds the shard's Furnisher configuration from the approved design data.

  python build_furnishers_config.py          writes ShardContent/data/configuration/furnishers.json

Inputs (all owner-approved 2026-10-08):
  docs/cosmetic-rewards/gold-sink/selection.json   the pieces sold in Britain (soldAt == "britain") with rarity, collection and price
  docs/cosmetic-rewards/*.json                     the catalog: each piece's graphics per facing
  layouts/counselor-guild-east.json (+ its site)   the showroom layout; checked by planner.py first, its placement becomes the hall's display items
Output: pieces (what the vendor sells and how a bought piece is built), the vendor's spot, and the hall's display items. The shard reads this
file at start (Configuration/furnishers.json) and, with the `furnishers` flag on, places the Furnisher and the hall from it, so a respawned
world gets them back without any hand work. Prices are the selection's (base 2,000 gp, rarity multipliers 1:2:4:8:16:35, ceiling 80,000).
"""
import json
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
WORKSPACE = os.path.normpath(os.path.join(HERE, "..", "..", ".."))
sys.path.insert(0, HERE)
import planner  # noqa: E402

SELECTION = os.path.join(WORKSPACE, "ShardContent", "docs", "cosmetic-rewards", "gold-sink", "selection.json")
LAYOUT = os.path.join(HERE, "layouts", "counselor-guild-east.json")
OUT = os.path.join(WORKSPACE, "ShardContent", "data", "configuration", "furnishers.json")
VENDOR = {"x": 1631, "y": 1668, "z": 15, "direction": "South"}      # just inside the double door, one tile off the entry lane
HALL_BOUNDS = [1622, 1654, 1641, 1680]                                # the hall (interior) and its forecourt


def main():
    sel = json.load(open(SELECTION, encoding="utf-8"))
    britain = [i for i in sel["items"] if i["soldAt"] == "britain"]
    pieces = []
    for it in sorted(britain, key=lambda i: (i["tier"], i["wing"], i["name"])):
        facings = []
        for facing, parts in planner.facings(it["id"]):
            facings.append({"facing": facing or "none",
                            "parts": [{"id": int(p["id"], 16), "dx": p["dx"], "dy": p["dy"], "dz": p["dz"], "hue": p.get("hue", 0) or 0} for p in parts]})
        kind = "item" if all(len(f["parts"]) == 1 for f in facings) else "deed"
        placement = planner.resolve(it["id"])["placement"]
        pieces.append({"id": it["id"], "name": it["name"], "rarity": it["tier"], "rarityName": it["tierName"], "collection": it["collection"],
                       "price": it["price"], "kind": kind, "placement": "wall" if placement.startswith("wall") else "rug" if placement == "ground-cover" else "floor",
                       "facings": facings})
    lay = json.load(open(LAYOUT, encoding="utf-8"))
    site = planner.Site(os.path.normpath(os.path.join(os.path.dirname(LAYOUT), lay["site"])))
    placed, _cells, problems = planner.check(site, [tuple(p) for p in lay["pieces"]])
    bad = [p for p in problems if not p.startswith("NOTE")]
    if bad:
        raise SystemExit("the showroom layout has problems, fix them first:\n  " + "\n  ".join(bad))
    hall = [{"piece": g["piece"], "id": g["id"], "x": g["x"], "y": g["y"], "z": g["z"], "hue": g["hue"]} for g in planner.client_layout(site, placed)]
    cfg = {"schemaVersion": 1,
           "note": "Generated by ShardContent/tools/world-decorating/build_furnishers_config.py from the approved selection and showroom layout. Edit the sources and regenerate, not this file.",
           "priceCeiling": sel["priceCap"],
           "stockDepth": 999,
           "vendor": VENDOR,
           "hall": {"bounds": HALL_BOUNDS, "items": hall},
           "pieces": pieces}
    with open(OUT, "w", encoding="utf-8", newline="\n") as f:
        json.dump(cfg, f, indent=1)
        f.write("\n")
    by = {}
    for p in pieces:
        by[p["rarity"]] = by.get(p["rarity"], 0) + 1
    print("wrote", OUT)
    print("%d pieces (%d items, %d deeds), by rarity %s; hall %d display items; total one-of-each %d gp" % (
        len(pieces), sum(p["kind"] == "item" for p in pieces), sum(p["kind"] == "deed" for p in pieces), dict(sorted(by.items())), len(hall), sum(p["price"] for p in pieces)))


if __name__ == "__main__":
    main()
