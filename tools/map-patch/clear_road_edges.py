"""Clears the forest along the roads so houses can be placed there (owner, 2026-10-20, an experiment: "clear the forest along
the roads here so that there is clear house-placeable grassland along the roads. Go out 10ish tiles from the road along it's
edges and clear out any objects that prevent house placement via the map statics").

Within RADIUS tiles of a road tile (the stock house-placement road land ids), inside the rectangle, every natural map static
that stock house placement refuses (HousePlacement.Check: impassable, or a surface that is not background) is taken out, with
the leaves or needles on the same tile. Man-made blockers (walls, fences, signs, buildings) are left and listed, so no building
loses a wall. Grass, flowers and other small pieces that do not block a house stay.

  python clear_road_edges.py X0 Y0 X1 Y1 OUT-PATCH.json [--radius 10]
Read from the pristine map (UO_ROOT=work/uodata-pristine-full). The patch's "remove" list goes to apply_statics_patch.py.
"""
import collections
import json
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.join(HERE, "..", "world-decorating"))
import uo_world as U  # noqa: E402

NATURAL = ("tree", "leaves", "needles", "log", "stump", "rock", "boulder", "bramble", "bush", "sapling", "fern", "vine",
           "branch", "trunk", "cactus", "shrub", "hedge", "reeds", "rushes", "foliage", "o'hii", "yucca", "plant", "mushroom")
MAN_MADE = ("wall", "fence", "post", "sign", "door", "window", "roof", "plank", "board", "stone", "brick", "column", "pillar")


def blocks_house(t):
    return bool(t.flags & U.IMP) or (bool(t.flags & U.SURF) and not t.flags & 0x1)


def natural(t):
    n = t.name.lower()
    return any(k in n for k in NATURAL) and not any(k in n for k in MAN_MADE) or bool(t.flags & U.FOLI)


def main(argv):
    radius = int(argv[argv.index("--radius") + 1]) if "--radius" in argv else 10
    x0, y0, x1, y1 = (int(v) for v in argv[:4])
    out = argv[4]
    reg = U.Region(x0 - radius - 1, y0 - radius - 1, x1 + radius + 1, y1 + radius + 1)
    roads = {(x, y) for x in range(reg.x0, reg.x1) for y in range(reg.y0, reg.y1) if U.is_road(reg.lid(x, y))}
    near = set()
    for rx, ry in roads:
        for dx in range(-radius, radius + 1):
            for dy in range(-radius, radius + 1):
                p = (rx + dx, ry + dy)
                if dx * dx + dy * dy <= radius * radius and x0 <= p[0] < x1 and y0 <= p[1] < y1 and p not in roads:
                    near.add(p)
    remove, left, removed_names = [], collections.Counter(), collections.Counter()
    for p in sorted(near):
        here = [(t, z) for t, z in reg.stat.get(p, []) if t < len(U.tiles)]
        cut = [(t, z) for t, z in here if blocks_house(U.tiles[t]) and natural(U.tiles[t])]
        if cut:  # the tree's leaves go with its trunk
            cut += [(t, z) for t, z in here if (t, z) not in cut and U.tiles[t].flags & U.FOLI]
        for t, z in cut:
            remove.append([t, p[0], p[1], z])
            removed_names[U.tiles[t].name] += 1
        for t, z in here:
            if (t, z) not in cut and blocks_house(U.tiles[t]):
                left["%s 0x%04X" % (U.tiles[t].name, t)] += 1
    json.dump({"about": "Statics cleared within %d tiles of the roads in %d-%d x %d-%d (Felucca) for house space, the owner's experiment of "
                        "2026-10-20. Generated by tools/map-patch/clear_road_edges.py from the pristine map; applied by "
                        "apply_statics_patch.py. Do not edit by hand." % (radius, x0, x1, y0, y1),
               "map": 0, "rect": [x0, y0, x1, y1], "radius": radius, "remove": remove},
              open(out, "w", encoding="utf-8", newline="\n"), indent=None)
    print("road tiles %d, tiles within %d of a road %d, statics removed %d" % (len(roads), radius, len(near), len(remove)))
    print("removed:", dict(removed_names.most_common()))
    print("blockers left (not natural):", dict(left.most_common()))


if __name__ == "__main__":
    main(sys.argv[1:])
