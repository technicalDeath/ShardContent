"""Which creatures does our game actually spawn?  (owner rule 2026-10-08: a figurine is fine when the creature it shows is present in our game)

Reads the era-reviewed Felucca spawners the shard generates (ModernUO/Distribution/Data/BritanniaRenaissance/Alpha2b/Spawns/*.json) and
writes
  data/species_in_game.json            -> the creature classes and the species tags a `monster:<species>` tag may use
  docs/cosmetic-rewards/Species-In-Game.md

A `monster:<species>` tag is accepted for a figurine when its words appear, in order, inside the kebab-case name of a spawned creature
(`fire-elemental` and `elemental` both pass for FireElemental; `crocodile` does not, the game has an Alligator).

  python speciesingame.py
"""
import collections
import json
import os
import re
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
WORKSPACE = os.path.normpath(os.path.join(HERE, "..", "..", ".."))
SPAWNS = os.path.join(WORKSPACE, "ModernUO", "Distribution", "Data", "BritanniaRenaissance", "Alpha2b", "Spawns")
OUT_JSON = os.path.join(HERE, "data", "species_in_game.json")
OUT_MD = os.path.join(WORKSPACE, "ShardContent", "docs", "cosmetic-rewards", "Species-In-Game.md")

# spawn entries that are people, vendors, reagents, crops, chests or camp markers rather than creatures
NOT_CREATURES = {
    "Alchemist", "AnimalTrainer", "Architect", "Armorer", "Artist", "Baker", "Banker", "Bard", "BardGuildmaster", "Blacksmith",
    "BlacksmithGuildmaster", "BlackPearl", "Bloodmoss", "Bowyer", "Butcher", "Carpenter", "ChaosGuard", "Cobbler", "Cook",
    "EscortableMage", "FarmableCabbage", "FarmableCarrot", "FarmableCotton", "FarmableOnion", "FarmableTurnip", "FarmableWheat",
    "Fisherman", "Furtrader", "Garlic", "Ginseng", "GolemController", "GrimmochDrummel", "HarborMaster", "Healer",
    "HealerGuildmaster", "Herbalist", "InnKeeper", "Jeweler", "KhaldunSummoner", "KhaldunZealot", "LysanderGathenwale", "Mage",
    "MageGuildmaster", "MandrakeRoot", "Mapmaker", "Merchant", "MerchantGuildmaster", "MinerGuildmaster", "Minter", "MorgBergen",
    "Noble", "Nightshade", "OrcCamp", "OrderGuard", "Peasant", "Provisioner", "RatCamp", "RealEstateBroker", "Scribe",
    "Shipwright", "SpidersSilk", "SulfurousAsh", "Tailor", "TailorGuildmaster", "Tanner", "TavaraSewel", "TavernKeeper",
    "TinkerGuildmaster", "TownCrier", "TreasureChestLevel1", "TreasureChestLevel2", "TreasureChestLevel3", "TreasureChestLevel4",
    "Waiter", "WanderingHealer", "Weaponsmith", "Weaver", "WarriorGuildmaster", "escortablewanderinghealer", "hirebard",
    "hirefighter", "hiresailor",
}


def kebab(name):
    return re.sub(r"(?<=[a-z0-9])(?=[A-Z])", "-", name).lower()


def main():
    where = collections.defaultdict(collections.Counter)
    for f in sorted(os.listdir(SPAWNS)):
        if not f.endswith(".json") or f in ("britain-vendor-overrides.json", "greater-britain-housing-spawner-relocations.json"):
            continue
        for sp in json.load(open(os.path.join(SPAWNS, f), encoding="utf-8")):
            for en in sp.get("entries", []) or []:
                if en["name"] not in NOT_CREATURES:
                    where[en["name"]][f[:-5]] += 1
    classes = sorted(where)
    names = {c: kebab(c) for c in classes}
    doc = {
        "source": "ModernUO/Distribution/Data/BritanniaRenaissance/Alpha2b/Spawns/*.json (era-reviewed Felucca spawners), read 2026-10-08",
        "rule": "a `monster:<species>` tag is valid when its words appear in order inside the kebab-case name of a spawned creature",
        "creatures": {c: {"kebab": names[c], "spawners": sum(where[c].values()), "where": dict(where[c].most_common(6))} for c in classes},
    }
    os.makedirs(os.path.dirname(OUT_JSON), exist_ok=True)
    with open(OUT_JSON, "w", encoding="utf-8") as f:
        json.dump(doc, f, indent=1)
        f.write("\n")
    lines = ["# Creatures present in our game", "",
             "*Generated by `ShardContent/tools/cosmetic-catalog/speciesingame.py` from the shard's own era-reviewed Felucca spawn data "
             "(`Alpha2b/Spawns/*.json`). Owner rule, 2026-10-08: **a monster figurine is fine as long as the creature it shows is present in our game.***", "",
             "A creature counts as present when one of those spawners places it (%d creature types; vendors, guild masters, reagents, crops, chests and "
             "camp markers are excluded). A creature that exists in the code but is never spawned (for example the mountain goat; the world has only goats) "
             "does not count until it is spawned. The catalog validator checks every figurine's `monster:` tag against this list." % len(classes), "",
             "| Creature | Spawners | Main places |", "| --- | ---: | --- |"]
    for c in classes:
        lines.append("| %s (`%s`) | %d | %s |" % (c, names[c], sum(where[c].values()),
                                                  ", ".join("%s %d" % (k, v) for k, v in where[c].most_common(4))))
    lines.append("")
    with open(OUT_MD, "w", encoding="utf-8") as f:
        f.write(chr(10).join(lines))
    print("creatures:", len(classes))


if __name__ == "__main__":
    main()
