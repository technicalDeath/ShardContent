"""A walkable route between two surface points, from the map's own data (generality step 5 support: routes planned at run time, with danger costs).

Pure and importable by every brain and test (standard library only, no Navrey, no bot state). walkgrid.bin is generated by make_walkgrid.py from the client's
map, statics and tiledata (water, rock, cliffs, trees and walls are not walkable; houses, doors and other mobiles are not known to it).

    import walkroute as wr
    wr.walkable(x, y)                         -> bool: could a character stand on this tile
    wr.snap(x, y, radius=40)                  -> the nearest walkable tile (x, y), or None
    wr.plan(frm, to, penalty=None, step=40)   -> {"steps", "exact", "path", "waypoints", "corners"} or None (no land route: an island, or a sea between)
         waypoints: tiles along the real path, every straight leg between two of them clear of obstacles, at most `step` tiles apart (feed a goto per leg)
         corners:   the same path simplified to its bends (10-tile tolerance), for display and for a coarse goto
         exact:     False when the tile-level search failed inside its corridor and the waypoints are the 4-tile-cell path (legs not guaranteed clear)
    wr.check_legs(points)                     -> [{"i", "a", "b", "blocked_at"}] for the straight legs between consecutive points that cross a tile that
                                                 cannot be walked (a first-trip waypoint list with a leg over water or a mountain)
    wr.repair(points, penalty=None, step=40)  -> the same list with every bad leg replaced by a planned walkable detour (None if a leg has no land route)
    wr.penalty_circles([(x, y, radius, factor), ...])   -> a penalty: cells inside a circle cost `factor` times as much (hard spawners, a camp)
    wr.penalty_from_memory(mem)               -> a penalty from the shared memory: cells where bots died, and cells it calls dangerous
    wr.penalty_merge(*penalties)              -> the larger factor per cell
A penalty is a dict {(x // 4, y // 4): factor >= 1}; the search multiplies a step's length by it, so a penalised region is crossed only when going
round costs more. Routes are model paths: the real client planner still walks each leg (a goto per waypoint is the intended use).
"""
import heapq
import math
import os
import struct
import zlib

DEFAULT_PATH = os.path.join(os.path.dirname(os.path.abspath(__file__)), "walkgrid.bin")
CELL = 4
MIN_OPEN = 3                                           # a 4x4 cell with fewer walkable tiles than this is not entered by the coarse search


def cheb(a, b):
    return max(abs(a[0] - b[0]), abs(a[1] - b[1]))


class WalkMap:
    def __init__(self, path=DEFAULT_PATH):
        raw = open(path, "rb").read()
        assert raw[:5] == b"WGRD1", "not a walkgrid file"
        self.W, self.H, n = struct.unpack_from("<HHI", raw, 5)
        self.bits = zlib.decompress(raw[13:13 + n])
        self.coarse = zlib.decompress(raw[13 + n:])
        self.CH = self.H // CELL
        assert len(self.bits) == self.W * self.H // 8 and len(self.coarse) == (self.W // CELL) * self.CH

    # ---- tiles ----------------------------------------------------------------------------------------------------------------------------------

    def walkable(self, x, y):
        if not (0 <= x < self.W and 0 <= y < self.H):
            return False
        i = x * self.H + y
        return (self.bits[i >> 3] >> (i & 7)) & 1 == 1

    def snap(self, x, y, radius=40):
        for r in range(radius + 1):
            for dx in range(-r, r + 1):
                for dy in range(-r, r + 1):
                    if max(abs(dx), abs(dy)) == r and self.walkable(x + dx, y + dy):
                        return (x + dx, y + dy)
        return None

    def open_cell(self, cx, cy):
        if not (0 <= cx < self.W // CELL and 0 <= cy < self.CH):
            return 0
        return self.coarse[cx * self.CH + cy]

    def leg_clear(self, a, b):
        """True when every tile of the straight line from a to b (Bresenham, 8-connected) is walkable."""
        return self.first_blocked(a, b) is None

    def first_blocked(self, a, b):
        x0, y0 = a
        x1, y1 = b
        dx, dy = abs(x1 - x0), abs(y1 - y0)
        sx, sy = (1 if x1 > x0 else -1), (1 if y1 > y0 else -1)
        err = dx - dy
        while True:
            if not self.walkable(x0, y0):
                return (x0, y0)
            if (x0, y0) == (x1, y1):
                return None
            e2 = 2 * err
            if e2 > -dy:
                err -= dy
                x0 += sx
            if e2 < dx:
                err += dx
                y0 += sy

    # ---- planning -------------------------------------------------------------------------------------------------------------------------------

    def _coarse_path(self, s, g, pen, min_open=MIN_OPEN):
        def h(n): return math.hypot(n[0] - g[0], n[1] - g[1])
        pq = [(h(s), 0.0, s)]
        came, best = {s: None}, {s: 0.0}
        while pq:
            _, d, cur = heapq.heappop(pq)
            if cur == g:
                break
            if d > best.get(cur, 1e18):
                continue
            for dx in (-1, 0, 1):
                for dy in (-1, 0, 1):
                    if not dx and not dy:
                        continue
                    n = (cur[0] + dx, cur[1] + dy)
                    o = self.open_cell(*n)
                    if o < min_open:
                        continue
                    if dx and dy and (self.open_cell(cur[0] + dx, cur[1]) < min_open or self.open_cell(cur[0], cur[1] + dy) < min_open):
                        continue
                    nd = d + math.hypot(dx, dy) * (1 + (16 - o) * 0.35) * (pen.get(n, 1.0) if pen else 1.0)
                    if nd < best.get(n, 1e18):
                        best[n], came[n] = nd, cur
                        heapq.heappush(pq, (nd + h(n), nd, n))
        if g not in came:
            return None
        path, c = [], g
        while c:
            path.append(c)
            c = came[c]
        path.reverse()
        return path

    def _tile_path(self, cpath, s, g, pen, width):
        cells = set()
        for cx, cy in cpath:
            for dx in range(-width, width + 1):
                for dy in range(-width, width + 1):
                    cells.add((cx + dx, cy + dy))

        def h(n):
            dx, dy = abs(n[0] - g[0]), abs(n[1] - g[1])
            return max(dx, dy) + 0.41 * min(dx, dy)

        pq = [(h(s), 0.0, s)]
        came, best = {s: None}, {s: 0.0}
        while pq:
            _, d, cur = heapq.heappop(pq)
            if cur == g:
                break
            if d > best.get(cur, 1e18):
                continue
            for dx in (-1, 0, 1):
                for dy in (-1, 0, 1):
                    if not dx and not dy:
                        continue
                    n = (cur[0] + dx, cur[1] + dy)
                    if (n[0] // CELL, n[1] // CELL) not in cells or not self.walkable(*n):
                        continue
                    if dx and dy and not (self.walkable(cur[0] + dx, cur[1]) and self.walkable(cur[0], cur[1] + dy)):
                        continue
                    nd = d + (1.414 if dx and dy else 1.0) * (pen.get((n[0] // CELL, n[1] // CELL), 1.0) if pen else 1.0)
                    if nd < best.get(n, 1e18):
                        best[n], came[n] = nd, cur
                        heapq.heappush(pq, (nd + h(n), nd, n))
        if g not in came:
            return None
        path, c = [], g
        while c:
            path.append(c)
            c = came[c]
        path.reverse()
        return path

    def waypoints(self, path, step=40):
        """Tiles along the path at most `step` apart whose straight legs are all clear: the farthest clear point within `step` each time."""
        if len(path) < 2:
            return list(path)
        out, i = [path[0]], 0
        while i < len(path) - 1:
            j = min(i + step, len(path) - 1)
            while j > i + 1 and not self.leg_clear(path[i], path[j]):
                j -= max(1, (j - i) // 4)
            out.append(path[j])
            i = j
        return out

    def corners(self, path, tol=10):
        def dp(pts):
            if len(pts) < 3:
                return pts
            (x1, y1), (x2, y2) = pts[0], pts[-1]
            L = math.hypot(x2 - x1, y2 - y1) or 1.0
            dmax, idx = 0.0, 0
            for k in range(1, len(pts) - 1):
                x, y = pts[k]
                d = abs((y2 - y1) * x - (x2 - x1) * y + x2 * y1 - y2 * x1) / L
                if d > dmax:
                    dmax, idx = d, k
            if dmax > tol:
                return dp(pts[:idx + 1])[:-1] + dp(pts[idx:])
            return [pts[0], pts[-1]]
        return dp(list(path))

    def plan(self, frm, to, penalty=None, step=40, tol=10, width=3):
        s, g = self.snap(frm[0], frm[1]), self.snap(to[0], to[1])
        if not s or not g:
            return None
        cs, cg = (s[0] // CELL, s[1] // CELL), (g[0] // CELL, g[1] // CELL)
        for c in (cs, cg):                              # a start or goal in a cell too tight for the coarse search: the nearest open cell
            if self.open_cell(*c) < MIN_OPEN:
                return self._plan_fine_only(s, g, penalty, step, tol)
        cpath = path = None
        for min_open in (MIN_OPEN, 6, 10):              # a path through barely open cells may not be walkable tile by tile: ask for roomier cells
            c = self._coarse_path(cs, cg, penalty, min_open)
            if c is None:
                break
            cpath = cpath or c
            for w in (width, 2 * width, 4 * width):
                path = self._tile_path(c, s, g, penalty, w)
                if path:
                    break
            if path:
                break
        if cpath is None:
            return None
        exact = path is not None
        if exact:
            wps = self.waypoints(path, step)
        else:                                           # the 4-tile-cell path: legs between its points are not guaranteed clear
            path = [(cx * CELL + CELL // 2, cy * CELL + CELL // 2) for cx, cy in cpath]
            k = max(1, step // CELL)
            wps = path[::k] + ([path[-1]] if (len(path) - 1) % k else [])
        return dict(steps=sum(cheb(path[k], path[k + 1]) for k in range(len(path) - 1)), exact=exact, path=path, waypoints=wps,
                    corners=self.corners(path, tol))

    def _plan_fine_only(self, s, g, penalty, step, tol):
        box = range(-1, 2)
        cells = [(s[0] // CELL + dx, s[1] // CELL + dy) for dx in box for dy in box]
        path = self._tile_path(cells, s, g, penalty, max(abs(g[0] - s[0]), abs(g[1] - s[1])) // CELL + 3)
        if not path:
            return None
        return dict(steps=len(path) - 1, exact=True, path=path, waypoints=self.waypoints(path, step), corners=self.corners(path, tol))

    def check_legs(self, points):
        out = []
        for i in range(len(points) - 1):
            a, b = tuple(points[i][:2]), tuple(points[i + 1][:2])
            bad = self.first_blocked(a, b)
            if bad:
                out.append(dict(i=i, a=a, b=b, blocked_at=bad))
        return out

    def repair(self, points, penalty=None, step=40):
        pts = [tuple(p[:2]) for p in points]
        out = [pts[0]]
        for a, b in zip(pts, pts[1:]):
            if self.leg_clear(a, b) and self.walkable(*a) and self.walkable(*b):
                out.append(b)
                continue
            r = self.plan(a, b, penalty, step)
            if r is None:
                return None
            out.extend(r["waypoints"][1:])
        return out


# ---- penalties --------------------------------------------------------------------------------------------------------------------------------

def penalty_circles(circles):
    pen = {}
    for x, y, radius, factor in circles:
        r = int(radius) // CELL + 1
        cx, cy = int(x) // CELL, int(y) // CELL
        for dx in range(-r, r + 1):
            for dy in range(-r, r + 1):
                if math.hypot((cx + dx) * CELL - x + CELL / 2, (cy + dy) * CELL - y + CELL / 2) <= radius:
                    k = (cx + dx, cy + dy)
                    pen[k] = max(pen.get(k, 1.0), float(factor))
    return pen


def penalty_from_memory(mem, cell_size=40, death_factor=2.0, dangerous_factor=6.0, cap=8.0):
    """Cells where bots died (more recent deaths cost more) and the cells the memory calls dangerous, as a penalty. `mem` is a SharedMemory (or anything
    with state["world"]["cells"] and, optionally, dangerous_cell(cell))."""
    pen = {}
    try:
        cells = mem.state["world"]["cells"]
    except Exception:
        return pen
    for key, c in list(cells.items()):
        deaths = float(c.get("deaths", 0.0))
        danger = False
        try:
            danger = bool(mem.dangerous_cell(key))
        except Exception:
            pass
        if deaths < 0.2 and not danger:
            continue
        factor = min(cap, 1.0 + death_factor * deaths) if deaths >= 0.2 else 1.0
        if danger:
            factor = max(factor, dangerous_factor)
        x0, y0 = (int(v) for v in key.split(","))
        for cx in range(x0 // CELL, (x0 + cell_size) // CELL):
            for cy in range(y0 // CELL, (y0 + cell_size) // CELL):
                pen[(cx, cy)] = max(pen.get((cx, cy), 1.0), factor)
    return pen


def penalty_merge(*pens):
    out = {}
    for p in pens:
        for k, v in (p or {}).items():
            out[k] = max(out.get(k, 1.0), v)
    return out


_default = None


def get(path=None):
    global _default
    if path is not None:
        return WalkMap(path)
    if _default is None:
        _default = WalkMap()
    return _default


def walkable(x, y): return get().walkable(x, y)
def snap(x, y, radius=40): return get().snap(x, y, radius)
def plan(frm, to, penalty=None, step=40, tol=10, width=3): return get().plan(frm, to, penalty, step, tol, width)
def check_legs(points): return get().check_legs(points)
def repair(points, penalty=None, step=40): return get().repair(points, penalty, step)
def leg_clear(a, b): return get().leg_clear(a, b)
